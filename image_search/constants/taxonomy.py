from __future__ import annotations

from dataclasses import dataclass

from image_search.constants.colors import COLOR_WORDS, normalize_color_label


@dataclass(frozen=True, slots=True)
class ConceptDefinition:
    key: str
    layer: str
    facet_key: str
    value_key: str
    display: str
    allowed_item_types: tuple[str, ...]
    patterns: tuple[str, ...] = ()
    aliases: tuple[str, ...] = ()
    preferred_evidence: str = "both"
    base_confidence: float = 0.76
    multi_value: bool = False
    max_values: int = 1
    search_only: bool = False
    is_filterable: bool = True


@dataclass(frozen=True, slots=True)
class ExtractionRule:
    name: str
    allowed_item_types: tuple[str, ...]
    patterns: tuple[str, ...]
    concept_keys: tuple[str, ...]
    preferred_evidence: str = "both"
    score_bonus: float = 0.1


def _concept(
    facet_key: str,
    value_key: str,
    display: str,
    *,
    allowed_item_types: tuple[str, ...],
    patterns: tuple[str, ...],
    preferred_evidence: str = "both",
    base_confidence: float = 0.76,
    multi_value: bool = False,
    max_values: int = 1,
    search_only: bool = False,
    is_filterable: bool | None = None,
    aliases: tuple[str, ...] = (),
) -> ConceptDefinition:
    return ConceptDefinition(
        key=f"{facet_key}:{value_key}",
        layer="visual",
        facet_key=facet_key,
        value_key=value_key,
        display=display,
        allowed_item_types=allowed_item_types,
        patterns=patterns,
        aliases=aliases,
        preferred_evidence=preferred_evidence,
        base_confidence=base_confidence,
        multi_value=multi_value,
        max_values=max_values,
        search_only=search_only,
        is_filterable=(not search_only) if is_filterable is None else is_filterable,
    )


def _rule(
    name: str,
    *,
    allowed_item_types: tuple[str, ...],
    patterns: tuple[str, ...],
    concept_keys: tuple[str, ...],
    preferred_evidence: str = "both",
    score_bonus: float = 0.1,
) -> ExtractionRule:
    return ExtractionRule(
        name=name,
        allowed_item_types=allowed_item_types,
        patterns=patterns,
        concept_keys=concept_keys,
        preferred_evidence=preferred_evidence,
        score_bonus=score_bonus,
    )


