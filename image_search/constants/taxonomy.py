def _concept(
    facet_key: str,
    value_key: str,
    display: str,
    *,
    allowed_item_types: tuple[str, ...],
    patterns: tuple[str, ...],
    preferred_evidence: str = "both",
    base_confidence: float = CONFIDENCE_LOW,
    multi_value: bool = False,
    max_values: int = 1,
    search_only: bool = False,
    is_filterable: bool | None = None,
    aliases: tuple[str, ...] = (),
) -> ConceptDefinition:
    resolved_search_only = search_only or facet_key in SEARCH_ONLY_FACETS
    return ConceptDefinition(
        key=f"{facet_key}:{value_key}",
        layer="visual",
        facet_key=facet_key,
        value_key=value_key,
        display=display,
        allowed_item_types=allowed_item_types,
        patterns=patterns,
        aliases=aliases,
        preferred_evidence=preferred_evidence,
        base_confidence=base_confidence,
        multi_value=multi_value,
        max_values=max_values,
        search_only=resolved_search_only,
        is_filterable=(
            (not resolved_search_only) if is_filterable is None else is_filterable
        ),
    )


def _rule(
    name: str,
    *,
    allowed_item_types: tuple[str, ...],
    patterns: tuple[str, ...],
    concept_keys: tuple[str, ...],
    preferred_evidence: str = "both",
    score_bonus: float = 0.1,
) -> ExtractionRule:
    return ExtractionRule(
        name=name,
        allowed_item_types=allowed_item_types,
        patterns=patterns,
        concept_keys=concept_keys,
        preferred_evidence=preferred_evidence,
        score_bonus=score_bonus,
    )


def _color_concepts() -> list[ConceptDefinition]:
    values = sorted(
        {normalize_color_label(value) for value in COLOR_WORDS} | {"multicolor"}
    )
    concepts: list[ConceptDefinition] = []
    for facet_key in ("color.primary", "color.secondary", "color.accent"):
        confidence = CONFIDENCE_HIGH if facet_key == "color.accent" else 0.9
        for value in values:
            concepts.append(
                ConceptDefinition(
                    key=f"{facet_key}:{value}",
                    layer="visual",
                    facet_key=facet_key,
                    value_key=value,
                    display=value.replace("_", " "),
                    allowed_item_types=ALL_ITEM_TYPES,
                    preferred_evidence="cv_only",
                    base_confidence=confidence,
                )
            )
    return concepts


