def _color_concepts() -> list[ConceptDefinition]:
    values = sorted({normalize_color_label(value) for value in COLOR_WORDS} | {"multicolor"})
    concepts: list[ConceptDefinition] = []
    for facet_key in ("color.primary", "color.secondary"):
        for value in values:
            concepts.append(
                ConceptDefinition(
                    key=f"{facet_key}:{value}",
                    layer="visual",
                    facet_key=facet_key,
                    value_key=value,
                    display=value.replace("_", " "),
                    allowed_item_types=ALL_ITEM_TYPES,
                    preferred_evidence="cv_only",
                    base_confidence=0.9,
                )
            )
    return concepts


